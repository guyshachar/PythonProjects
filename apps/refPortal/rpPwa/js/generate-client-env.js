#!/usr/bin/env node

/**
 * Client Environment Generator
 * Generates client-env.js file with environment variables for client-side use
 */

const fs = require('fs');
const path = require('path');

// Load environment variables from .env file
require('dotenv').config({ path: process.env.envFilePath });

/**
 * Generate client environment configuration
 */
function generateClientEnv() {
    const timestamp = new Date().toISOString();
    
    // Default values for fallback
    const defaults = {
        PWA_HTTP_PORT: '8082',
        PWA_HTTPS_PORT: '8443',
        API_BASE_URL: 'https://pwa-dev.refereex.com:5003',
        WSS_BASE_URL: 'pwa-dev.refereex.com:5003',
        NODE_ENV: 'development',
        DEBUG_MODE: 'true',
        VERSION: 'v1.0.0',
        APP_NAME: 'RefereeX',
        APP_SHORT_NAME: 'RefereeX',
        CORS_ORIGIN: '*'
    };
    
    // Server environment variables (safe for client-side)
    const clientEnv = {
        // Server ports
        PWA_HTTP_PORT: process.env.PWA_HTTP_PORT || defaults.PWA_HTTP_PORT,
        PWA_HTTPS_PORT: process.env.PWA_HTTPS_PORT || defaults.PWA_HTTPS_PORT,
        
        // Base URLs
        PWA_BASE_URL: process.env.PWA_BASE_URL || `https://localhost:${process.env.PWA_HTTPS_PORT || defaults.PWA_HTTPS_PORT}`,
        API_BASE_URL: process.env.API_BASE_URL || defaults.API_BASE_URL,
        WSS_BASE_URL: process.env.WSS_BASE_URL || defaults.WSS_BASE_URL,
        
        // Service URLs from environment
        apiServiceUrlBase: process.env.apiServiceUrlBase || process.env.API_BASE_URL || defaults.API_BASE_URL,
        rootServiceUrlBase: process.env.rootServiceUrlBase || 'https://www.refereex.com/',
        docsServiceUrlBase: process.env.docsServiceUrlBase || 'https://www.refereex.com/docs/',
        
        // Environment info
        NODE_ENV: process.env.NODE_ENV || defaults.NODE_ENV,
        DEBUG_MODE: process.env.DEBUG_MODE === 'true' || process.env.DEBUG === 'true' || defaults.DEBUG_MODE === 'true',
        
        // Build info
        BUILD_TIME: timestamp,
        VERSION: process.env.VERSION || defaults.VERSION,
        
        // Feature flags from environment
        FEATURES: {
            PUSH_NOTIFICATIONS: process.env.PUSH_NOTIFICATIONS !== 'false',
            PUSH_NOTIFICATIONS_MUST: process.env.PUSH_NOTIFICATIONS_MUST === 'true',
            OFFLINE_SUPPORT: process.env.OFFLINE_SUPPORT !== 'false',
            BACKGROUND_SYNC: process.env.BACKGROUND_SYNC !== 'false',
            INSTALL_PROMPT: process.env.INSTALL_PROMPT !== 'false',
            CHAT_SYNC: process.env.CHAT_SYNC !== 'false',
            MAX_GPS_ACCURACY: 30,
            START_MONITORING_HOURS_BEFORE_GAME: 3,
            SPEED_THRESHOLD: 10,
            MIN_DISTANCE_THRESHOLD: 0,
        },
        
        // App info
        APP_NAME: process.env.APP_NAME || defaults.APP_NAME,
        APP_SHORT_NAME: process.env.APP_SHORT_NAME || defaults.APP_SHORT_NAME,
        
        // Security settings (safe for client)
        SECURITY: {
            ENABLE_PIN: process.env.ENABLE_PIN === 'true',
            PIN_LENGTH: parseInt(process.env.PIN_LENGTH) || 4,
            MAX_PAIR_ATTEMPTS: parseInt(process.env.MAX_PAIR_ATTEMPTS) || 3,
        },
        
        // CORS origin
        CORS_ORIGIN: process.env.CORS_ORIGIN || defaults.CORS_ORIGIN,
        
        // Additional client-safe environment variables
        ...(process.env.CLIENT_SAFE_VARS ? JSON.parse(process.env.CLIENT_SAFE_VARS) : {})
    };
    
    return clientEnv;
}

/**
 * Generate the client-env.js file content
 */
function generateClientEnvFile() {
    const clientEnv = generateClientEnv();
    const timestamp = new Date().toISOString();
    
    const fileContent = `// Auto-generated client environment configuration
// Generated at: ${timestamp}
// DO NOT EDIT THIS FILE MANUALLY - IT WILL BE OVERWRITTEN

window.CLIENT_ENV = ${JSON.stringify(clientEnv, null, 2)};

// Export for ES6 modules
if (typeof module !== 'undefined' && module.exports) {
    module.exports = window.CLIENT_ENV;
}

// Make available globally
if (typeof global !== 'undefined') {
    global.CLIENT_ENV = window.CLIENT_ENV;
}

// Log environment info (only in debug mode)
if (window.CLIENT_ENV.DEBUG_MODE) {
    console.log('🌍 Client environment loaded:', window.CLIENT_ENV);
    console.log('📅 Generated at:', window.CLIENT_ENV.BUILD_TIME);
    console.log('🏷️ Version:', window.CLIENT_ENV.VERSION);
}

// Export for TypeScript/ES6 modules
export default window.CLIENT_ENV;
export const CLIENT_ENV = window.CLIENT_ENV;
`;

    return fileContent;
}

/**
 * Write the client-env.js file
 */
function writeClientEnvFile() {
    try {
        const filePath = path.join(__dirname, 'client-env.js');
        const content = generateClientEnvFile();
        
        // Ensure the js directory exists
        const jsDir = path.dirname(filePath);
        if (!fs.existsSync(jsDir)) {
            fs.mkdirSync(jsDir, { recursive: true });
        }
        
        // Write the file
        fs.writeFileSync(filePath, content, 'utf8');
        
        console.log('✅ Client environment file generated successfully');
        console.log(`📁 File: ${filePath}`);
        console.log(`📅 Generated at: ${new Date().toISOString()}`);
        
        // Show environment summary
        const clientEnv = generateClientEnv();
        console.log('\n📋 Client Environment Summary:');
        console.log(`  NODE_ENV: ${clientEnv.NODE_ENV}`);
        console.log(`  DEBUG_MODE: ${clientEnv.DEBUG_MODE}`);
        console.log(`  API_BASE_URL: ${clientEnv.API_BASE_URL}`);
        console.log(`  PWA_BASE_URL: ${clientEnv.PWA_BASE_URL}`);
        console.log(`  WSS_BASE_URL: ${clientEnv.WSS_BASE_URL}`);
        console.log(`  HTTP_PORT: ${clientEnv.PWA_HTTP_PORT}`);
        console.log(`  HTTPS_PORT: ${clientEnv.PWA_HTTPS_PORT}`);
        
        return true;
    } catch (error) {
        console.error('❌ Error generating client environment file:', error.message);
        return false;
    }
}

/**
 * Main function
 */
function main() {
    console.log('🚀 Generating client environment configuration...');
    console.log('='.repeat(50));
    
    const success = writeClientEnvFile();
    
    if (success) {
        console.log('\n✅ Client environment generation completed successfully!');
        console.log('💡 The client-env.js file is ready for use in your PWA.');
    } else {
        console.log('\n❌ Client environment generation failed!');
        process.exit(1);
    }
}

// Run if called directly
if (require.main === module) {
    main();
}

// Export functions for use in other modules
module.exports = {
    generateClientEnv,
    generateClientEnvFile,
    writeClientEnvFile
};
